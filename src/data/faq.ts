/**
 * What a question is matched on: its own words, the answer, and the alternate
 * phrasings the sheet gives - someone searching "who can approve" should reach
 * the approvals rows without having to use the sheet's own wording.
 */
export function searchFaq(entries: readonly FaqEntry[], query: string): FaqEntry[] {
  const terms = query.toLowerCase().split(/\s+/).filter(Boolean)
  if (!terms.length) return [...entries]
  return entries.filter((entry) => {
    const haystack = `${entry.question} ${entry.answer} ${entry.keywords.join(" ")} ${entry.category}`.toLowerCase()
    return terms.every((term) => haystack.includes(term))
  })
}

